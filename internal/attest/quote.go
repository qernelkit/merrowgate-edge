// Package attest checks TPM quotes from sensor gateways. A quote is the TPM's
// signed statement of its PCR values and of the challenge we sent; the
// attestation key it is signed with was recorded when the device was paired.
package attest

import (
	"bytes"
	"crypto"
	"crypto/rsa"
	"crypto/sha256"
	"crypto/x509"
	"encoding/binary"
	"errors"
	"fmt"
)

// Quote is what a device posts: the TPMS_ATTEST structure exactly as the TPM
// signed it, and the signature.
type Quote struct {
	Attested  []byte `json:"attested"`
	Signature []byte `json:"signature"`
}

const (
	tpmGenerated   = 0xff544347 // "\xffTCG"
	tpmStQuoteType = 0x8018
)

var errQuote = errors.New("attest: malformed quote")

// Verify checks q against the device's attestation key (DER) and the challenge the
// gateway issued.
func Verify(attestKey []byte, q Quote, challenge []byte) error {
	parsed, err := x509.ParsePKIXPublicKey(attestKey)
	if err != nil {
		return fmt.Errorf("attest: key on record: %w", err)
	}
	pub, ok := parsed.(*rsa.PublicKey)
	if !ok {
		return fmt.Errorf("attest: unexpected key type %T", parsed)
	}
	digest := sha256.Sum256(q.Attested)
	if err := rsa.VerifyPSS(pub, crypto.SHA256, digest[:], q.Signature, &rsa.PSSOptions{SaltLength: rsa.PSSSaltLengthEqualsHash}); err != nil {
		return fmt.Errorf("attest: quote signature: %w", err)
	}
	extra, err := extraData(q.Attested)
	if err != nil {
		return err
	}
	if !bytes.Equal(extra, challenge) {
		return errors.New("attest: quote is not for the current challenge")
	}
	return nil
}

// extraData reads the qualifying data (our challenge) out of a TPMS_ATTEST:
// magic (4), type (2), qualifiedSigner (TPM2B), extraData (TPM2B), ...
func extraData(attested []byte) ([]byte, error) {
	if len(attested) < 8 {
		return nil, errQuote
	}
	if binary.BigEndian.Uint32(attested[0:4]) != tpmGenerated {
		return nil, fmt.Errorf("%w: not generated by a TPM", errQuote)
	}
	if binary.BigEndian.Uint16(attested[4:6]) != tpmStQuoteType {
		return nil, fmt.Errorf("%w: not a quote", errQuote)
	}
	rest := attested[6:]
	_, rest, err := sized(rest) // qualifiedSigner
	if err != nil {
		return nil, err
	}
	extra, _, err := sized(rest)
	return extra, err
}

func sized(b []byte) (field, rest []byte, err error) {
	if len(b) < 2 {
		return nil, nil, errQuote
	}
	n := int(binary.BigEndian.Uint16(b))
	if len(b) < 2+n {
		return nil, nil, errQuote
	}
	return b[2 : 2+n], b[2+n:], nil
}
